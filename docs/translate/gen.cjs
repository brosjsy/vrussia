// node gen.cjs   builds src/scenes-ru-gen-core.ts and src/scenes-ru-gen-<n>.ts from dict.json + rules.cjs.
// A scene is generated when every piece of it (title halves, sentences, choices, fixed result lines) has a Russian piece. The files keep each Russian piece once
// and a scene is a list of piece numbers (a city or university name is a number too), which the core expands when the language is loaded.
const fs = require('fs');
const path = require('path');
const a = require('./all-full.json').filter(s => !s.built);
const { cities, unis, jobs } = require('./ents.json');
const ents = require('./ents-ru.json');
const dict = JSON.parse(fs.readFileSync('dict.json', 'utf8'));
const derive = require('./rules.cjs');
const NAMES = [...cities, ...unis, ...jobs];                                   // the global name numbers used by the scenes
const names = [...jobs.map(n => [n, 'JOB']), ...unis.map(n => [n, 'UNI']), ...cities.map(n => [n, 'CITY'])].sort((x, y) => y[0].length - x[0].length);
const re = new RegExp(names.map(([n]) => n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
const type = Object.fromEntries(names);
const sp = t => t.split(/(?<=[.!?])\s+(?=[A-Z"“({])/).map(x => x.trim()).filter(Boolean);
function piece(p) { const caps = []; const n = p.replace(re, m => { caps.push(NAMES.indexOf(m)); return '{' + type[m] + '}'; }); return { n, caps }; }
function ru(p) { const { n, caps } = piece(p); const r = dict[n] ?? derive(n); return r === undefined || r === null ? null : { r, caps }; }

const dir = path.join(__dirname, '..', '..', 'src');
for (const f of fs.readdirSync(dir)) if (/^scenes-ru-gen(-\d+|-core)?\.ts$/.test(f)) fs.unlinkSync(path.join(dir, f));

// parts of about 100,000 characters of output each (so that each file stays under 40 KB gzipped)
const parts = []; let cur = null;
const startPart = () => { cur = { P: [], idx: new Map(), D: [], size: 0 }; parts.push(cur); };
const refOf = x => { let i = cur.idx.get(x.r); if (i === undefined) { i = cur.P.length; cur.P.push(x.r); cur.idx.set(x.r, i); cur.size += x.r.length + 4; } return x.caps.length ? [i, ...x.caps] : i; };
let done = 0, missing = 0;
for (const s of a) {
  const title = s.title.split(': ').map(ru), text = sp(s.text).map(ru);
  const ch = s.choices.map(c => [ru(c.t), c.fixed && c.then ? sp(c.then).map(ru) : []]);
  const ok = !title.includes(null) && !text.includes(null) && ch.every(([t, th]) => t !== null && !th.includes(null));
  if (!ok) { missing++; continue; }
  if (!cur || cur.size > 62000) startPart();
  const entry = [s.id, title.map(refOf), text.map(refOf), ch.map(([t, th]) => [refOf(t), th.map(refOf)])];
  cur.size += JSON.stringify(entry).length + 2; cur.D.push(entry); done++;
}

const forms = Object.fromEntries(cities.map(c => [c, ents.cities[c]]));
fs.writeFileSync(path.join(dir, 'scenes-ru-gen-core.ts'), `/* Generated by docs/translate/gen.cjs. Expands the compact Russian scene files (scenes-ru-gen-<n>.ts) into scenes. */
import type { SceneRu } from './scenes-ru';
export type Ref = number | number[];
type Entry = [string, Ref[], Ref[], [Ref, Ref[]][]];
const NAMES: string[] = ${JSON.stringify(NAMES)};
const CITY: Record<string, string[]> = ${JSON.stringify(forms)};
const UNI: Record<string, string> = ${JSON.stringify(ents.unis)};
const JOB: Record<string, string> = ${JSON.stringify(ents.jobs)};
const ROLE: Record<string, number> = { '': 0, in: 1, to: 2, from: 3, of: 4 };
export function expand(P: string[], D: Entry[]): Record<string, SceneRu> {
  const one = (r: Ref): string => {
    const [i, ...caps] = Array.isArray(r) ? r : [r];
    let k = 0;
    return P[i].replace(/\\{(CITY|UNI)(?::([a-z]+))?\\}/g, (_, t: string, role?: string) => { const n = NAMES[caps[k++]]; return t === 'UNI' ? UNI[n] ?? n : CITY[n]?.[ROLE[role ?? '']] ?? n; });
  };
  const out: Record<string, SceneRu> = {};
  for (const [id, title, text, ch] of D) out[id] = { title: title.map(one).join(': '), text: text.map(one).join(' '), choices: ch.map(([t, th]) => [one(t), th.map(one).join(' ')] as [string, string]) };
  return out;
}
`);
parts.forEach((p, i) => fs.writeFileSync(path.join(dir, `scenes-ru-gen-${i + 1}.ts`), `/* Generated by docs/translate/gen.cjs from the reviewed phrase list docs/translate/dict.json. Do not edit by hand. */
import { expand } from './scenes-ru-gen-core';
import type { Ref } from './scenes-ru-gen-core';
const P: string[] = ${JSON.stringify(p.P)};
const D: [string, Ref[], Ref[], [Ref, Ref[]][]][] = ${JSON.stringify(p.D)};
export const GEN: Record<string, import('./scenes-ru').SceneRu> = expand(P, D);
`));
fs.writeFileSync(path.join(dir, 'scenes-ru-gen.ts'), `/* Generated by docs/translate/gen.cjs. The parts are separate files, fetched together when the game is in Russian. */
import type { SceneRu } from './scenes-ru';
export const loadGenerated = async (): Promise<Record<string, SceneRu>> => Object.assign({}, ${parts.map((_, i) => `(await import('./scenes-ru-gen-${i + 1}')).GEN`).join(', ')});
`);
console.log('scenes done', done, 'missing a piece', missing, 'parts', parts.length, parts.map(p => p.size).join(','));
