/** The title, site and blurb of a service in the game's language. */
export function flowText(f: { id: string; title: string; site: string; blurb: string }): { title: string; site: string; blurb: string } {
  const r = lang() === 'ru' ? RU[f.id] : undefined;
  return r ? { title: r[0], site: r[1], blurb: r[2] } : { title: f.title, site: f.site, blurb: f.blurb };
}
