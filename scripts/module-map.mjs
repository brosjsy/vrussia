/* Writes docs/MODULES.md: one line for every source file, taken from the comment at the top of the file, so the map of the code never goes stale.
     node scripts/module-map.mjs          rewrite docs/MODULES.md
   A file without a top comment is listed as "(no header comment)": add one (what the file is for, in one or two sentences) and run this again. */
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const AREAS = [
  ['src', 'The game in the browser (rules, screens, data)', /^src\/[^/]+\.ts$/],
  ['src/content', 'Scenarios (the stories): each file adds scenarios with S()', /^src\/content\//],
  ['src/platform', 'Platform features: tutorial, privacy, languages, reports, classes, daily game, packs, guide, audio', /^src\/platform\//],
  ['server/src', 'The server (Fastify + PostgreSQL): accounts, saves, leaderboard, classes, statistics', /^server\/src\//],
  ['scripts', 'Developer scripts', /^scripts\//],
];
function walk(dir, out = []) {
  for (const n of readdirSync(dir)) {
    if (n === 'node_modules' || n === 'dist' || n.startsWith('.')) continue;
    const p = join(dir, n).split('\\').join('/');
    if (statSync(p).isDirectory()) walk(p, out); else if (/\.(ts|mjs|cjs)$/.test(n) && !/\.d\.ts$/.test(n)) out.push(p);
  }
  return out;
}
function header(file) {
  const t = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const m = t.match(/^\s*(?:\/\*+\s*([\s\S]*?)\*\/|((?:\/\/[^\n]*\n?)+))/);
  if (!m) return '(no header comment)';
  const raw = (m[1] ?? m[2].replace(/^\/\/\s?/gm, '')).replace(/\n\s*\*?\s*/g, ' ').replace(/\s+/g, ' ').trim();
  const first = raw.match(/^.{20,260}?\.(?=\s|$)/);
  return (first ? first[0] : raw.slice(0, 200)).replace(/\|/g, '/');
}
const files = [...walk('src'), ...walk('server/src'), ...walk('scripts')].filter(f => !/scripts\/(thesis|memos)\//.test(f));
let out = '# Map of the code\n\nGenerated by `node scripts/module-map.mjs` from the comment at the top of each file. Do not edit by hand: change the comment in the file and run the script again. How the parts fit together: `docs/ARCHITECTURE.md`.\n';
for (const [, title, re] of AREAS) {
  const list = files.filter(f => re.test(f)).sort();
  out += `\n## ${title}\n\n| File | What it is for |\n|---|---|\n${list.map(f => `| \`${f}\` | ${header(f)} |`).join('\n')}\n`;
}
writeFileSync('docs/MODULES.md', out);
console.log('docs/MODULES.md:', files.length, 'files,', out.split('(no header comment)').length - 1, 'without a header comment');
